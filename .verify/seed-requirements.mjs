/**
 * Give an existing app its opening contract.
 *
 * New apps build this up from their first turn. An app mid-flight has its
 * requirements scattered through a thread that has already scrolled, which is the
 * situation the column exists to fix — so the first one is written by hand, from
 * what the owner actually asked for.
 */
import fs from 'fs'
import { createClient } from '@libsql/client'
const env = fs.readFileSync(process.env.ENV_FILE ?? '.env.local', 'utf8')
const get = (k) => (env.match(new RegExp('^' + k + '=(.*)$', 'm')) || [])[1]?.trim().replace(/^["']|["']$/g, '')
const client = createClient({ url: get('DATABASE_URL'), authToken: get('TURSO_AUTH_TOKEN') })

const REQUIREMENTS = `- Every comment is generated by AI at post time and is specific to THAT post's text and image. Never a fixed pool, never the same reply twice, never a generic "congrats".
- The AI reads the attached image as well as the text. An image that does not match the post gets called out for it.
- Outcome drives volume and tone: a viral post gets many replies and they celebrate; a flop gets harsh criticism or complete silence (zero comments) — silence is a valid, intended outcome.
- Critical and questioning replies appear on negative outcomes, not just praise on positive ones.
- Metrics animate on reveal: likes, views and reposts tick up over a few seconds, and replies appear staggered rather than all at once. A flop visibly does nothing.
- The post stays on screen while that plays out.
- The X logo is the real one, top left.
- Share produces a working link. Generated images are uploaded to the CDN first so the payload stays within the save limit.
- Dark theme, X/Twitter styling.`

const { rows } = await client.execute({
  sql: `SELECT id, title, requirements FROM playground_apps WHERE title LIKE ? LIMIT 1`,
  args: ['%Launch Simulator%'],
})
if (!rows[0]) { console.log('not found'); process.exit(1) }
if (rows[0].requirements && !process.argv.includes('--force')) {
  console.log('already has requirements; pass --force to replace'); process.exit(0)
}
await client.execute({
  sql: `UPDATE playground_apps SET requirements = ? WHERE id = ?`,
  args: [REQUIREMENTS, rows[0].id],
})
console.log(`seeded contract for "${rows[0].title}":\n`)
console.log(REQUIREMENTS)
process.exit(0)
